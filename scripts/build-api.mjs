// Bundles the Express API into one plain-JavaScript ESM file for Vercel.
// Source files use `./module.ts` import specifiers, which Vercel's Node runtime
// cannot load directly; bundling removes them. npm packages stay external so
// Vercel's file tracer packages them from node_modules.
import { build } from 'esbuild';
import { mkdir } from 'node:fs/promises';

await mkdir('api', { recursive: true });
await build({
  entryPoints: ['server/vercel-entry.ts'],
  outfile: 'api/index.mjs',
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  packages: 'external',
  sourcemap: false,
  legalComments: 'none',
  banner: { js: '// GENERATED by scripts/build-api.mjs from server/ - do not edit by hand.' },
  logLevel: 'info',
});
console.log('Built the Vercel API function at api/index.mjs.');
