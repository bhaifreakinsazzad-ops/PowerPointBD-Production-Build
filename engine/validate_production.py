"""Independent Static output gate. Structural evidence is not desktop playback proof."""
import argparse
import json
from pathlib import Path
from zipfile import ZipFile
from pptx import Presentation
from phase0 import validate
from content_contract import validate_content


def validate_production(output: Path, slide_count: int, language_mode: str, content=None) -> dict:
    try:
        if output.stat().st_size > 64 * 1024 * 1024:
            raise ValueError('PACKAGE_TOO_LARGE')
        with ZipFile(output) as package:
            entries = package.infolist()
            if len(entries) > 4096 or sum(entry.file_size for entry in entries) > 128 * 1024 * 1024:
                raise ValueError('PACKAGE_RESOURCE_LIMIT')
        report = validate(output, 'static', expected_slide_count=slide_count,
                          require_bengali=language_mode in ('bn', 'bilingual'))
        presentation = Presentation(output)
        if len(presentation.slides) != slide_count:
            report['errors'].append('Reopened slide count mismatch')
            report['passed'] = False
        if content is not None:
            content = validate_content(content, slide_count)
            if (content['language'] != language_mode or presentation.core_properties.title != content['title']
                    or presentation.core_properties.language != content['language']):
                report['errors'].append('Content metadata mismatch')
            for index, (slide, expected) in enumerate(zip(presentation.slides, content['slides'])):
                # Role names are generated by our template, not chosen by the AI.
                titles = [s for s in slide.shapes if s.name == 'Role_Title']
                bodies = [s for s in slide.shapes if s.name == 'Role_Body']
                if len(titles) != 1 or titles[0].text != expected['title']:
                    report['errors'].append('Slide title mismatch')
                if len(bodies) != 1 or [p.text for p in bodies[0].text_frame.paragraphs] != expected['bullets']:
                    report['errors'].append('Slide body mismatch')
                if not slide.has_notes_slide or slide.notes_slide.notes_text_frame.text != expected['notes']:
                    report['errors'].append('Speaker notes mismatch')
                footers = [s for s in slide.shapes if s.name == 'Role_SlideNumber']
                if len(footers) != 1 or footers[0].text != f'{index + 1} / {slide_count}':
                    report['errors'].append('Slide number mismatch')
                allowed = {'Role_Title', 'Role_Body', 'Role_SlideNumber'}
                if any(s.name not in allowed for s in slide.shapes):
                    report['errors'].append('Unexpected slide shape')
        report['passed'] = not report['errors']
        report.update(slide_count=slide_count, desktop_playback='UNVERIFIED',
                      content_source='VALIDATED_CUSTOMER_DRAFT' if content is not None else 'PLACEHOLDER_NOT_AI_GENERATED',
                      visual_approval='UNVERIFIED', validator='validate_production-v2')
        return report
    except Exception:
        return {'passed': False, 'errors': ['PACKAGE_VALIDATION_FAILED']}


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--output', required=True, type=Path)
    parser.add_argument('--slide-count', required=True, type=int)
    parser.add_argument('--language-mode', required=True, choices=['bn', 'en', 'bilingual'])
    parser.add_argument('--content', type=Path)
    args = parser.parse_args()
    content = None
    if args.content:
        if args.content.stat().st_size > 1048576:
            raise ValueError('CONTENT_TOO_LARGE')
        content = json.loads(args.content.read_text(encoding='utf-8'))
    print(json.dumps(validate_production(args.output, args.slide_count, args.language_mode, content)))
